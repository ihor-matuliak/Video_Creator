"""Selection dedupe, diversity order and the candidate cap (ADR 041 §7, docs/06 §7).

Candidates of one source are compared by their half-open ``[start_ms, end_ms)`` intervals
and by the transcript evidence ids they cite. Two candidates are the same event only when
the temporal signal holds AND they share an evidence id, so repeated speech at a different
time survives. An existing clip whose evidence is not comparable (``evidence_ids is None``)
matches on the temporal signal alone.

Pure: standard library and ``clipforge.domain.categories`` only, no I/O.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass, replace
from typing import Final, Literal

from clipforge.domain.categories import CATEGORIES, validate_categories

# ``(evidence id, start_ms, end_ms)`` of one transcript word or segment.
EvidenceEntry = tuple[str, int, int]

ExistingKind = Literal["reviewed", "suggested"]
SuppressionKind = Literal[
    "already_reviewed", "duplicate_of_suggested", "duplicate_in_run", "over_cap"
]

# docs/06 §7: IoU >= 0.65 or overlap / min_len >= 0.8. Compared as integers with the
# denominators multiplied out, so no rounding is involved.
IOU_PERCENT: Final = 65
COVER_PERCENT: Final = 80

# ADR 041 §7: a candidate may be picked for diversity only while its rank is within this
# many points of the best remaining candidate, so diversity never lifts a weak scene.
DIVERSITY_RANK_WINDOW: Final = 5


@dataclass(frozen=True, slots=True)
class Item:
    """One candidate of this run. ``key`` is a unique local id generated by the backend."""

    key: str
    start_ms: int
    end_ms: int
    evidence: tuple[EvidenceEntry, ...]
    categories: tuple[str, ...]
    rank: int
    visual_review_required: bool


@dataclass(frozen=True, slots=True)
class Existing:
    """A clip of the same source that candidates must not duplicate.

    ``evidence_ids=None`` means the evidence is not comparable (manual clip, or ids that are
    not in the current transcript); the temporal signal alone then makes a duplicate.
    """

    clip_id: str
    start_ms: int
    end_ms: int
    evidence_ids: frozenset[str] | None
    kind: ExistingKind


@dataclass(frozen=True, slots=True)
class Suppressed:
    """A candidate left out of ``kept``. ``duplicate_of`` is a clip id or a kept item key."""

    key: str
    kind: SuppressionKind
    duplicate_of: str | None


@dataclass(frozen=True, slots=True)
class Selection:
    """``kept`` is in diversity order and holds at most ``max_candidates`` items.

    ``suppressed`` lists dedupe decisions in processing order, then ``over_cap`` items in
    diversity order.
    """

    kept: tuple[Item, ...]
    suppressed: tuple[Suppressed, ...]


def dedupe_and_rank(
    items: Sequence[Item], existing: Sequence[Existing], *, max_candidates: int
) -> Selection:
    """Dedupe run candidates against existing clips, order them for diversity, apply the cap.

    Items are processed by rank (highest first), then start, then key. Each one is checked
    against reviewed clips (``already_reviewed``), then suggested clips
    (``duplicate_of_suggested``), then candidates already kept in this run, which it is merged
    into (``duplicate_in_run``). The result does not depend on the order of either input.
    """
    if max_candidates < 0:
        raise ValueError("max_candidates must not be negative")
    _check_items(items)
    _check_existing(existing)

    reviewed = sorted((clip for clip in existing if clip.kind == "reviewed"), key=_clip_order)
    suggested = sorted((clip for clip in existing if clip.kind == "suggested"), key=_clip_order)

    kept: list[Item] = []
    suppressed: list[Suppressed] = []
    for item in sorted(items, key=_processing_order):
        ids = _evidence_ids(item.evidence)
        clip = _first_existing_match(item, ids, reviewed)
        if clip is not None:
            suppressed.append(Suppressed(item.key, "already_reviewed", clip.clip_id))
            continue
        clip = _first_existing_match(item, ids, suggested)
        if clip is not None:
            suppressed.append(Suppressed(item.key, "duplicate_of_suggested", clip.clip_id))
            continue
        index = _first_kept_match(item, ids, kept)
        if index is None:
            kept.append(item)
        else:
            target = kept[index]
            kept[index] = _merge(target, item)
            suppressed.append(Suppressed(item.key, "duplicate_in_run", target.key))

    ordered = _diversity_order(kept)
    suppressed.extend(Suppressed(item.key, "over_cap", None) for item in ordered[max_candidates:])
    return Selection(kept=tuple(ordered[:max_candidates]), suppressed=tuple(suppressed))


def _check_items(items: Sequence[Item]) -> None:
    keys = [item.key for item in items]
    if len(set(keys)) != len(keys):
        raise ValueError("item keys must be unique")
    for item in items:
        _check_span(f"item {item.key!r}", item.start_ms, item.end_ms)
        if not item.categories:
            raise ValueError(f"item {item.key!r} has no categories")
        validate_categories(item.categories)


def _check_existing(existing: Sequence[Existing]) -> None:
    clip_ids = [clip.clip_id for clip in existing]
    if len(set(clip_ids)) != len(clip_ids):
        raise ValueError("existing clip ids must be unique")
    for clip in existing:
        _check_span(f"existing clip {clip.clip_id!r}", clip.start_ms, clip.end_ms)


def _check_span(name: str, start_ms: int, end_ms: int) -> None:
    if not 0 <= start_ms < end_ms:
        raise ValueError(f"{name}: expected 0 <= start_ms < end_ms, got [{start_ms}, {end_ms})")


def _clip_order(clip: Existing) -> tuple[int, int, str]:
    return (clip.start_ms, clip.end_ms, clip.clip_id)


def _processing_order(item: Item) -> tuple[int, int, str]:
    return (-item.rank, item.start_ms, item.key)


def _evidence_ids(evidence: Sequence[EvidenceEntry]) -> frozenset[str]:
    return frozenset(entry[0] for entry in evidence)


def _temporal_signal(a_start: int, a_end: int, b_start: int, b_end: int) -> bool:
    overlap = min(a_end, b_end) - max(a_start, b_start)
    if overlap <= 0:
        return False
    union = (a_end - a_start) + (b_end - b_start) - overlap
    shorter = min(a_end - a_start, b_end - b_start)
    return overlap * 100 >= IOU_PERCENT * union or overlap * 100 >= COVER_PERCENT * shorter


def _is_duplicate(
    item: Item,
    ids: frozenset[str],
    other_start: int,
    other_end: int,
    other_ids: frozenset[str] | None,
) -> bool:
    if not _temporal_signal(item.start_ms, item.end_ms, other_start, other_end):
        return False
    return other_ids is None or not ids.isdisjoint(other_ids)


def _first_existing_match(
    item: Item, ids: frozenset[str], clips: Sequence[Existing]
) -> Existing | None:
    for clip in clips:
        if _is_duplicate(item, ids, clip.start_ms, clip.end_ms, clip.evidence_ids):
            return clip
    return None


def _first_kept_match(item: Item, ids: frozenset[str], kept: Sequence[Item]) -> int | None:
    for index, target in enumerate(kept):
        if _is_duplicate(item, ids, target.start_ms, target.end_ms, _evidence_ids(target.evidence)):
            return index
    return None


def _merge(kept: Item, incoming: Item) -> Item:
    """Fold a duplicate into the kept item. Its start, end and rank do not change."""
    present = set(kept.categories) | set(incoming.categories)
    evidence = list(kept.evidence)
    for entry in incoming.evidence:
        inside = kept.start_ms <= entry[1] and entry[2] <= kept.end_ms
        if inside and entry not in evidence:
            evidence.append(entry)
    return replace(
        kept,
        categories=tuple(category for category in CATEGORIES if category in present),
        evidence=tuple(evidence),
        visual_review_required=kept.visual_review_required or incoming.visual_review_required,
    )


def _diversity_order(pool: Sequence[Item]) -> list[Item]:
    """Greedy order: among candidates within the rank window, take the least-used category."""
    remaining = list(pool)
    picked: list[Item] = []
    used: dict[str, int] = {}
    while remaining:
        best = max(item.rank for item in remaining)
        eligible = [item for item in remaining if item.rank >= best - DIVERSITY_RANK_WINDOW]
        chosen = min(eligible, key=lambda item: _diversity_key(item, used))
        remaining.remove(chosen)
        picked.append(chosen)
        for category in chosen.categories:
            used[category] = used.get(category, 0) + 1
    return picked


def _diversity_key(item: Item, used: Mapping[str, int]) -> tuple[int, int, int, str]:
    least_used = min(used.get(category, 0) for category in item.categories)
    return (least_used, -item.rank, item.start_ms, item.key)
